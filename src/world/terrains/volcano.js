const INK = '#29271f';
const PAPER = '#f4efdf';
const EMBER = '#a45d47';
const SLATE = '#66675e';

// A broken caldera, read through pale ash, basalt folds, and a thin molten seam.
export default function drawTerrain({ line, curve, shape, random }) {
  const stroke = (points, opacity = .6, z = 1, color = INK) => line(points, color, opacity, z);
  const contour = (points, opacity = .4, z = 1, color = INK) => curve(points, color, opacity, z);

  // The plume loosens as it rises; its open edges preserve the paper sky.
  contour([[-5, 12], [-9, 17], [-7, 21], [-10, 25], [-8, 29], [-15, 33]], .29, -5);
  contour([[4, 12], [6, 18], [1, 22], [3, 27], [-2, 31], [-1, 34]], .25, -5);
  contour([[-2, 16], [-4, 21], [-1, 25], [-5, 29]], .18, -5, EMBER);
  contour([[-9, 23], [-13, 26], [-12, 30], [-18, 32], [-24, 32.6]], .16, -5);
  contour([[1, 28], [-3, 32], [-8, 33.1]], .15, -5);
  contour([[-7, 18], [-4, 19], [1, 18.1], [4, 19]], .13, -4.9);
  contour([[-10, 26], [-7, 27], [-3, 26.4]], .13, -4.9);
  contour([[-14, 30], [-12, 31.4], [-8, 31.7]], .12, -4.9);
  contour([[-40, 22], [-34, 22.4], [-28, 22]], .17, -5, SLATE);
  contour([[23, 28], [30, 28.2], [36, 27.8]], .16, -5, SLATE);
  contour([[29, 26.8], [35, 26.9], [40, 26.5]], .1, -5, SLATE);

  // Low distant ridges keep the crater's silhouette singular and broad.
  stroke([[-44, -9], [-38, -1], [-33, 3], [-29, 1], [-24, 4], [-17, -3]], .25, -4, SLATE);
  stroke([[17, -5], [24, 1], [29, 3], [33, 1], [38, 5], [44, -4]], .24, -4, SLATE);
  stroke([[-33, 3], [-34, -1], [-31, -4]], .15, -4, SLATE);
  stroke([[38, 5], [37, -.5], [40, -4]], .16, -4, SLATE);
  for (let i = 0; i < 12; i++) {
    const t = i / 11;
    stroke([[-39 + t * 11, -3 - t * 5], [-37.5 + t * 11, -4.5 - t * 5]], .12, -3.9, SLATE);
    stroke([[28 + t * 11, -2 - t * 3], [29.5 + t * 11, -3.4 - t * 3]], .12, -3.9, SLATE);
  }

  // An offset rim, with its right wall collapsed into the lava's escape gully.
  const massif = [[-43, -23], [-37, -14], [-31, -8], [-27, -1], [-23, 5], [-20, 11], [-16, 14], [-9, 15], [-3, 12.7], [3, 13.2], [10, 11.3], [16, 8], [19, 2], [25, -6], [31, -10], [43, -23], [31, -30], [-28, -30]];
  shape(massif, PAPER, 1, -2);
  stroke(massif.slice(0, 16), .77, -1.9);
  shape([[-9, 15], [-11, 9], [-17, 4], [-19, -3], [-27, -10], [-31, -19], [-40, -24], [-28, -30], [-12, -17], [-9, -4], [-2, 5], [3, 9], [-3, 12.7]], SLATE, .055, -1.85);
  shape([[10, 11.3], [16, 8], [19, 2], [25, -6], [31, -10], [43, -23], [31, -30], [22, -21], [18, -12], [15, -5], [12, 1]], SLATE, .12, -1.85);
  shape([[20, -5], [26, -12], [31, -16], [34, -24], [30, -27], [23, -17]], INK, .035, -1.8);

  // Far wall, recessed bowl, and the chipped lip have separate contour weights.
  contour([[-20, 11], [-15, 11.8], [-9, 11.6], [-3, 10], [4, 10.6], [10, 9.3], [16, 8]], .64, -1.7);
  shape([[-18, 10.8], [-12, 7.1], [-6, 5.4], [1, 5.5], [7, 6.8], [12, 8.6], [5, 9.6], [-3, 9], [-10, 10.7]], SLATE, .11, -1.65);
  contour([[-18, 10.8], [-14, 7.7], [-7, 5.8], [0, 5.6], [6, 6.5], [12, 8.6]], .72, -1.5);
  contour([[-17, 9.1], [-12, 6.3], [-5, 4.6], [2, 4.8], [7, 5.9]], .36, -1.4);
  contour([[-15, 7.6], [-10, 5.1], [-5, 3.9], [0, 4]], .23, -1.4);
  stroke([[-20, 11], [-20.7, 7.5], [-23, 5]], .49, -1.4);
  stroke([[-16, 14], [-15.1, 12.6], [-16.5, 11.8]], .39, -1.4);
  stroke([[-9, 15], [-8.1, 12.8], [-10, 11.7]], .35, -1.4);
  stroke([[-3, 12.7], [-3.8, 11.1]], .33, -1.4);
  stroke([[10, 11.3], [9.3, 10], [12, 8.6], [11, 6.3], [14, 4.5]], .54, -1.4);
  for (let i = 0; i < 15; i++) {
    const t = i / 14;
    const x = -15 + t * 22;
    const y = 9.2 - Math.sin(t * Math.PI) * 2.6;
    stroke([[x, y], [x + .4, y - .8 - random() * .8]], .25, -1.3);
  }

  // Long fractured planes describe cooled lava without filling the mountain.
  const folds = [
    [[-23, 5], [-25, -2], [-30, -8], [-31, -13], [-37, -21]],
    [[-18, 5], [-20, -1], [-24, -4], [-23, -9], [-29, -17], [-30, -23]],
    [[-11, 4], [-13, -.5], [-12, -5], [-17, -9], [-16, -14]],
    [[-6, 3.8], [-7, -2], [-3, -8], [-5, -14], [-2, -20]],
    [[14, 4.5], [17, -.5], [16, -5], [21, -11], [22, -18]],
    [[19, 2], [21, -4], [27, -9], [26, -14], [33, -23]],
    [[-36, -14], [-32, -15], [-29, -18], [-24, -20]],
    [[19, -15], [24, -17], [27, -22], [32, -24]],
  ];
  folds.forEach((points, i) => stroke(points, i < 6 ? .39 : .28, -1.2));
  contour([[-30, -6], [-26, -7], [-23, -6], [-20, -8]], .24, -1.2);
  contour([[-34, -13], [-30, -11.8], [-26, -13.3]], .2, -1.2);
  contour([[20, -7], [23, -7.5], [25, -10]], .27, -1.2);
  for (let i = 0; i < 30; i++) {
    const t = i / 29;
    const x = -21 - t * 13;
    const y = 3 - t * 24;
    stroke([[x, y], [x + 1.6 + random() * 1.5, y - .9 - random()]], .21, -1.1);
    if (i % 3 === 0) stroke([[x + .4, y - .8], [x + 2.3, y - 2]], .13, -1.1, SLATE);
  }
  for (let i = 0; i < 26; i++) {
    const t = i / 25;
    const x = 15 + t * 17;
    const y = 1 - t * 25;
    stroke([[x, y], [x + 2.2 + random(), y - .8 - random()]], .23, -1.1);
  }
  for (let i = 0; i < 14; i++) {
    const t = i / 13;
    stroke([[-10 + t * 5, -3 - t * 15], [-8.6 + t * 5, -4.4 - t * 15]], .17, -1.1, SLATE);
  }

  // Two fine edges and a pale wash carry the heat down a broken channel.
  const lavaLeft = [[5, 6], [7, 2], [5.5, -2], [8.3, -6], [7.4, -10], [12, -15], [9, -20], [8.2, -24], [13, -31]];
  const lavaRight = [[8, 6.8], [10, 1.8], [8.8, -2], [11.4, -6.1], [10.7, -9.7], [15.5, -15], [12.5, -20.4], [12, -24.1], [17.5, -31]];
  shape([...lavaLeft, ...lavaRight.toReversed()], EMBER, .065, -.8);
  contour(lavaLeft, .77, -.7, EMBER);
  contour(lavaRight, .65, -.7, EMBER);
  contour([[6.7, 4], [8.2, 1], [7.4, -2], [9.8, -6]], .3, -.6, EMBER);
  contour([[10.1, -11.9], [13.4, -15], [11.6, -18.3]], .34, -.6, EMBER);
  contour([[11, -25], [12.8, -27.7], [15.4, -30.2]], .29, -.6, EMBER);
  contour([[11.2, -7], [15.3, -9], [17.5, -12.9], [21.4, -14.1]], .47, -.65, EMBER);
  contour([[11.7, -8.7], [14.5, -10.3], [16.2, -13.9]], .26, -.65, EMBER);
  contour([[7.2, -18.6], [4, -19.5], [1.9, -22], [-1.4, -23]], .31, -.65, EMBER);

  // Basalt shelves hold the foreground; individual facets stay translucent.
  const shelfLeft = [[-44, -26], [-39, -22], [-34, -22.4], [-30, -18.7], [-26, -20], [-23, -24], [-17, -26.3], [-11, -31], [-12, -34], [-32, -33]];
  const shelfRight = [[20, -26], [23, -21.2], [28, -20.7], [31, -23.5], [36, -22.5], [40, -25.7], [44, -27], [43, -33], [29, -34], [23, -31]];
  shape(shelfLeft, PAPER, 1, 0);
  shape(shelfRight, PAPER, 1, 0);
  stroke(shelfLeft.slice(0, 9), .7, .1);
  stroke(shelfRight.slice(0, 7), .71, .1);
  shape([[-30, -18.7], [-26, -20], [-23, -24], [-17, -26.3], [-11, -31], [-12, -34], [-22, -30], [-27, -26]], SLATE, .12, .1);
  shape([[28, -20.7], [31, -23.5], [36, -22.5], [40, -25.7], [44, -27], [43, -33], [37, -30], [32, -29]], SLATE, .11, .1);
  stroke([[-39, -22], [-38, -28.3], [-34, -31]], .46, .2);
  stroke([[-34, -22.4], [-34.8, -27.4], [-30.5, -30.7]], .4, .2);
  stroke([[-30, -18.7], [-30.5, -24], [-27, -26], [-26, -31]], .51, .2);
  stroke([[-26, -20], [-27.4, -23.8], [-24, -26.6], [-22, -30]], .4, .2);
  stroke([[23, -21.2], [24.5, -25.7], [23, -29]], .36, .2);
  stroke([[28, -20.7], [27.1, -25], [30.1, -27.4], [29, -32.6]], .47, .2);
  stroke([[36, -22.5], [34.4, -26], [37, -29.7], [36.8, -32]], .4, .2);
  contour([[-43, -28.6], [-37, -28.7], [-32, -30.2]], .23, .3);
  contour([[31, -30.3], [36, -30.8], [41, -30]], .23, .3);
  for (let i = 0; i < 17; i++) {
    const t = i / 16;
    stroke([[-27 + t * 10, -23.8 - t * 7], [-25.7 + t * 10, -25.2 - t * 7]], .23, .4);
    stroke([[31 + t * 8, -25.7 - t * 5.2], [32 + t * 8, -27.4 - t * 5.2]], .2, .4);
  }

  // A switchback on cool ground turns toward a small stepping-stone crossing.
  contour([[-14.2, 6], [-16.8, 1.7], [-15, -2.7], [-20.8, -7.6], [-12.8, -10.7], [-19, -14.5], [-9.1, -16.9], [-3.4, -19.1], [2.8, -21.5], [6.8, -22.7]], .58, .7);
  contour([[-13.7, 5.6], [-16, 1.5], [-14, -2.6], [-19.2, -7.4], [-11.2, -10.8], [-17, -14.3], [-8.4, -15.8], [-2.8, -18], [3.2, -20.4], [7, -21.7]], .28, .7);
  contour([[14, -24], [18, -26.4], [21.4, -29.2], [29, -33]], .6, .7);
  contour([[15, -23.5], [19, -25.8], [22.7, -28.7], [31, -32.8]], .29, .7);
  const stone = (x, y, w, h) => {
    const points = [[x - w, y], [x - w * .7, y + h * .65], [x + w * .25, y + h], [x + w, y + h * .3], [x + w * .7, y - h * .25]];
    shape(points, PAPER, 1, .9);
    stroke([...points, points[0]], .7, 1);
    stroke([[x - w * .7, y + h * .65], [x + w * .12, y + h * .28], [x + w * .7, y - h * .25]], .3, 1.1);
    contour([[x - w * .9, y - h * .4], [x, y - h * .6], [x + w, y - h * .4]], .2, .8, EMBER);
  };
  stone(7.4, -22.5, 1.35, .8);
  stone(10.5, -23, 1.25, .9);
  stone(13.7, -23.5, 1.4, 1);
  stone(-36.5, -25.5, 2.2, 1.6);
  stone(37.2, -26.5, 2, 1.8);
  stone(-3, -28.2, 1.5, 1);
  stone(19, -31.8, 1.1, .8);

  // Embers are brief dashes, ash is almost absent outside the plume.
  [[-3, 17, .5], [2, 19.4, .6], [-6, 22.5, .4], [3, 24.1, .5], [-3.8, 28, .35], [-10, 31, .3], [7, 15.2, .45], [-10.5, 18.4, .3]].forEach(([x, y, s]) => {
    stroke([[x, y], [x + s * .42, y + s]], .46, -.2, EMBER);
  });
  for (let i = 0; i < 23; i++) {
    const x = -40 + random() * 80;
    const y = -30 - random() * 3.4;
    if (x > 5 && x < 19) continue;
    stroke([[x, y], [x + .5 + random() * 1.3, y + .1]], .18, 1.2);
  }
  [[-4, -10], [1, -15], [20, -18], [-30, -16], [30, -13]].forEach(([x, y]) => {
    stroke([[x - .4, y], [x, y + .6], [x + .8, y + .2]], .31, -.5);
  });
}
