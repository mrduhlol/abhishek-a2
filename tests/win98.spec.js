import { expect, test } from '@playwright/test'

test('Windows 98 boots into a portfolio with independent windows and project search', async ({ page }) => {
  await page.goto('/win98/', { waitUntil: 'domcontentloaded' })
  const desktop = page.getByRole('navigation', { name: 'Desktop shortcuts' })
  await expect(desktop).toBeVisible({ timeout: 30_000 })
  await expect(desktop.getByRole('button', { name: 'DocuType' })).toHaveCSS('cursor', /win98-icons\/pointer\.png/)

  const welcome = page.getByRole('region', { name: 'Welcome', exact: true })
  await expect(welcome.getByRole('heading', { name: 'Welcome' })).toBeVisible()
  await expect(welcome.getByRole('link')).toHaveCount(0)
  const titleBar = welcome.locator('.win98-titlebar')
  const bounds = await titleBar.boundingBox()
  await page.mouse.move(bounds.x + 120, bounds.y + 9)
  await page.mouse.down()
  await page.mouse.move(bounds.x + 180, bounds.y + 49)
  await page.mouse.up()
  await expect.poll(async () => (await titleBar.boundingBox()).x).toBe(bounds.x + 60)

  await desktop.getByRole('button', { name: 'My Computer' }).dblclick()
  const computer = page.getByRole('region', { name: 'My Computer' })
  await expect(computer.getByRole('heading', { level: 1 })).toHaveText('Hi, I’m Abhishek.')
  await expect(welcome).toBeVisible()
  await computer.getByRole('button', { name: 'Maximize window' }).click()
  await expect(computer.getByRole('button', { name: 'Restore window size' })).toBeVisible()
  await computer.getByRole('button', { name: 'Minimize window' }).click()
  await expect(computer).toBeHidden()
  await page.locator('#win98-task-about').click()
  await expect(computer).toBeVisible()
  await computer.getByRole('button', { name: 'Close window' }).click()
  await expect(page.locator('#win98-task-about')).toHaveCount(0)
  await welcome.getByRole('button', { name: 'Close window' }).click()

  await desktop.getByRole('button', { name: 'My Documents' }).dblclick()
  const documents = page.getByRole('region', { name: 'My Documents' })
  await expect(documents.getByRole('heading', { level: 1 })).toHaveText('Projects')
  await documents.getByRole('button', { name: 'DocuType' }).click()
  const docutype = page.getByRole('region', { name: 'DocuType' })
  await expect(docutype.getByRole('img', { name: 'DocuType extension popup' })).toBeVisible()
  await docutype.getByRole('button', { name: 'Close window' }).click()
  await documents.getByRole('button', { name: 'Close window' }).click()

  await desktop.getByRole('button', { name: 'Black Jack' }).click()
  const blackjack = page.getByRole('region', { name: 'Black Jack' })
  await expect(blackjack.getByRole('heading', { name: 'Black Jack' })).toBeVisible()
  await blackjack.getByRole('button', { name: 'Close window' }).click()

  await page.getByRole('button', { name: 'Open Internet Explorer' }).click()
  const browser = page.getByRole('region', { name: 'Internet Explorer' })
  await expect(browser.getByRole('heading', { name: 'Google' })).toBeVisible()
  await browser.getByRole('searchbox', { name: 'Search Abhishek’s projects' }).fill('Orbit')
  await browser.getByRole('button', { name: 'Search Projects' }).click()
  await browser.getByRole('button', { name: 'Orbit' }).click()
  await expect(page.getByRole('link', { name: 'View Orbit source on GitHub' }))
    .toHaveAttribute('href', 'https://github.com/mrduhlol/Orbit')

  await page.setViewportSize({ width: 375, height: 812 })
  const start = page.getByRole('button', { name: 'Start', exact: true })
  await start.click()
  await expect(page.getByRole('navigation', { name: 'Start menu' }).getByText('windows.a', { exact: true })).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(start).toBeFocused()
  await start.click()
  await page.getByRole('navigation', { name: 'Start menu' }).getByRole('button', { name: 'Outlook Express' }).click()
  const outlook = page.getByRole('region', { name: 'Outlook Express' })
  await expect(outlook.getByRole('link', { name: 'abhishek.a2534@gmail.com' }))
    .toHaveAttribute('href', 'mailto:abhishek.a2534@gmail.com')
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(375)
})
